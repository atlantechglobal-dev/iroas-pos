// Operator-only, idempotent URY configuration for the Saffron & Fig demo.
// Creates (only if missing) the records the demo needs and nothing else:
//   - Customer "IROAS Website Guest"            (self-ordering default customer)
//   - URY Self Ordering Profile for the restaurant (pickup only, one order per session)
// Opening hours, closures and the restaurant Address are NOT written here —
// they are entered by the restaurant in URY desk.
//
//   node scripts/ury-demo-setup.js [--restaurant "Demo Restaurant"]           (dry run)
//   node scripts/ury-demo-setup.js [--restaurant "Demo Restaurant"] --apply
//
// Uses the operator credential (URY_USERNAME/URY_PASSWORD or URY_API_KEY/SECRET)
// and the standard Frappe `frappe.client.insert` method. Secrets are never printed.

import 'dotenv/config'
import { getDoc, getList, uryPost, UryError } from '../src/integrations/ury/uryClient.js'

const args = process.argv.slice(2)
const apply = args.includes('--apply')
const restaurantName = (() => {
  const i = args.indexOf('--restaurant')
  return i >= 0 ? args[i + 1] : 'Demo Restaurant'
})()

const GUEST_CUSTOMER = 'IROAS Website Guest'

async function exists(doctype, name) {
  try {
    await getDoc(doctype, name)
    return true
  } catch (err) {
    if (err instanceof UryError && err.code === 'not_found') return false
    throw err
  }
}

const restaurant = (await getDoc('URY Restaurant', restaurantName)).docs[0]
const profiles = (await getList('POS Profile', { fields: ['name', 'restaurant', 'branch', 'disabled'], filters: { restaurant: restaurantName } }))
  .filter((p) => p.restaurant === restaurantName && p.branch === restaurant.branch && p.disabled !== 1)
if (profiles.length !== 1) {
  console.log(`Expected exactly one active POS Profile for "${restaurantName}", found ${profiles.length}. Nothing done.`)
  process.exit(1)
}
const posProfile = profiles[0].name
const profileName = `${restaurantName} Website`

const plan = []
if (!(await exists('Customer', GUEST_CUSTOMER))) plan.push('customer')
const existingProfiles = await getList('URY Self Ordering Profile', {
  fields: ['name', 'restaurant', 'branch', 'pos_profile', 'enabled'],
  filters: { restaurant: restaurantName },
})
if (existingProfiles.length) {
  console.log('Existing self-ordering profile(s) for this restaurant (left unchanged):')
  console.table(existingProfiles)
} else {
  plan.push('profile')
}

console.log(`Restaurant "${restaurantName}" · branch "${restaurant.branch}" · POS profile "${posProfile}"`)
if (!plan.length) {
  console.log('Nothing to create.')
  process.exit(0)
}
console.log(`${apply ? 'Creating' : 'Would create'}: ${plan.join(', ')}`)
if (!apply) {
  console.log('Dry run. Re-run with --apply to write these records to URY.')
  process.exit(0)
}

if (plan.includes('customer')) {
  const body = await uryPost('frappe.client.insert', {
    doc: { doctype: 'Customer', customer_name: GUEST_CUSTOMER, customer_type: 'Individual', customer_group: 'Individual' },
  })
  console.log(`Created Customer "${body?.message?.name}"`)
}

if (plan.includes('profile')) {
  const body = await uryPost('frappe.client.insert', {
    doc: {
      doctype: 'URY Self Ordering Profile',
      __newname: profileName,
      profile_name: profileName,
      restaurant: restaurantName,
      branch: restaurant.branch,
      pos_profile: posProfile,
      default_customer: GUEST_CUSTOMER,
      enabled: 1,
      enable_qr_table_ordering: 0,
      enable_qr_pickup_ordering: 1,
      enable_kiosk_ordering: 0,
      allow_add_to_running_table: 0,
      enable_request_bill: 0,
      enable_customer_payment: 0,
      enable_payment_link: 0,
      enable_pay_at_counter: 1,
      session_idle_timeout_minutes: 30,
    },
  })
  const created = body?.message || {}
  console.log(
    `Created URY Self Ordering Profile "${created.name}" (pickup ordering on, add-to-running-order off, ` +
      `QR signing secret ${created.qr_signing_secret ? 'generated by URY' : 'NOT set — URY did not generate one'}).`,
  )
}
